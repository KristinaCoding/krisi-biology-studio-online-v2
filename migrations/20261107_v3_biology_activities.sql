-- Biology Studio v3: additive PostgreSQL schema for interactive activities.
-- PREPARATION ONLY. Review against the live schema and back up before applying.
-- This migration does not alter or delete existing students, lessons, or bookings.
-- UUID identifiers match public.student_profiles / public.teacher_profiles.
BEGIN;

CREATE TABLE IF NOT EXISTS public.biology_activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id UUID NOT NULL REFERENCES public.teacher_profiles(id),
    student_id UUID NOT NULL REFERENCES public.student_profiles(id),
    title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 150),
    topic TEXT NOT NULL CHECK (char_length(topic) BETWEEN 1 AND 100),
    questions JSONB NOT NULL CHECK (jsonb_typeof(questions) = 'array'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS biology_activities_teacher_student_idx
    ON public.biology_activities (teacher_id, student_id);

CREATE TABLE IF NOT EXISTS public.biology_activity_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id BIGINT NOT NULL UNIQUE REFERENCES public.biology_activities(id),
    student_id UUID NOT NULL REFERENCES public.student_profiles(id),
    answers JSONB NOT NULL CHECK (jsonb_typeof(answers) = 'array'),
    score INTEGER NOT NULL CHECK (score >= 0),
    total INTEGER NOT NULL CHECK (total > 0 AND score <= total),
    completed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMIT;
