-- Biology Studio v3: remaining PostgreSQL tables (additive draft).
-- Do not execute before backup and verifying actual public.* schemas.
-- UUID teacher/student IDs follow existing Supabase profiles.
BEGIN;

CREATE TABLE IF NOT EXISTS public.homework (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 teacher_id UUID NOT NULL REFERENCES public.teacher_profiles(id),
 student_id UUID NOT NULL REFERENCES public.student_profiles(id),
 title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 150),
 instructions TEXT NOT NULL CHECK (char_length(instructions) BETWEEN 1 AND 5000),
 due_at TIMESTAMPTZ NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS homework_teacher_student_idx ON public.homework(teacher_id,student_id);
CREATE TABLE IF NOT EXISTS public.homework_submissions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 homework_id BIGINT NOT NULL UNIQUE REFERENCES public.homework(id) ON DELETE CASCADE,
 student_id UUID NOT NULL REFERENCES public.student_profiles(id),
 answer TEXT NOT NULL CHECK (char_length(answer) BETWEEN 1 AND 10000),
 submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 grade TEXT CHECK (char_length(grade)<=40),
 feedback TEXT CHECK (char_length(feedback)<=4000),
 reviewed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS homework_submissions_student_idx ON public.homework_submissions(student_id);

CREATE TABLE IF NOT EXISTS public.calendar_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 teacher_id UUID NOT NULL REFERENCES public.teacher_profiles(id),
 student_id UUID NOT NULL REFERENCES public.student_profiles(id),
 title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 150),
 starts_at TIMESTAMPTZ NOT NULL,
 notes TEXT NOT NULL DEFAULT '' CHECK (char_length(notes)<=2000),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS calendar_events_teacher_time_idx ON public.calendar_events(teacher_id,starts_at);
CREATE INDEX IF NOT EXISTS calendar_events_student_time_idx ON public.calendar_events(student_id,starts_at);

CREATE TABLE IF NOT EXISTS public.classroom_rooms (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 teacher_id UUID NOT NULL REFERENCES public.teacher_profiles(id),
 student_id UUID NOT NULL REFERENCES public.student_profiles(id),
 title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 150),
 meeting_url TEXT NOT NULL CHECK (char_length(meeting_url) BETWEEN 1 AND 2000),
 scheduled_at TIMESTAMPTZ NOT NULL,
 notes TEXT NOT NULL DEFAULT '' CHECK (char_length(notes)<=3000),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS classroom_rooms_teacher_time_idx ON public.classroom_rooms(teacher_id,scheduled_at);
CREATE INDEX IF NOT EXISTS classroom_rooms_student_time_idx ON public.classroom_rooms(student_id,scheduled_at);

CREATE TABLE IF NOT EXISTS public.certificates (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 teacher_id UUID NOT NULL REFERENCES public.teacher_profiles(id),
 student_id UUID NOT NULL REFERENCES public.student_profiles(id),
 title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 150),
 description TEXT NOT NULL DEFAULT '' CHECK (char_length(description)<=2000),
 issued_on DATE NOT NULL DEFAULT CURRENT_DATE,
 certificate_code TEXT NOT NULL UNIQUE CHECK (char_length(certificate_code)=24),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS certificates_teacher_student_idx ON public.certificates(teacher_id,student_id);

-- Store only metadata in Postgres. Object bytes must be kept in a private,
-- durable Supabase Storage bucket; never on Render's ephemeral filesystem.
CREATE TABLE IF NOT EXISTS public.materials (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 teacher_id UUID NOT NULL REFERENCES public.teacher_profiles(id),
 student_id UUID NOT NULL REFERENCES public.student_profiles(id),
 title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 150),
 original_name TEXT NOT NULL CHECK (char_length(original_name) BETWEEN 1 AND 255),
 storage_bucket TEXT NOT NULL,
 storage_path TEXT NOT NULL UNIQUE,
 uploaded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS materials_teacher_student_idx ON public.materials(teacher_id,student_id);

CREATE TABLE IF NOT EXISTS public.email_notifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 teacher_id UUID REFERENCES public.teacher_profiles(id),
 recipient TEXT NOT NULL,
 subject TEXT NOT NULL CHECK (char_length(subject)<=180),
 message TEXT NOT NULL CHECK (char_length(message)<=10000),
 status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','sent')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 sent_at TIMESTAMPTZ,
 last_error TEXT
);
CREATE INDEX IF NOT EXISTS email_notifications_status_id_idx ON public.email_notifications(status,id);

COMMIT;
